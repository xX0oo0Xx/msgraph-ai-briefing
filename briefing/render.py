from __future__ import annotations

from datetime import datetime
from html import escape

from .sanitize import EmailItem, EventItem
from .schema import Briefing, EmailTriage

SECTION_ORDER = [
    ("urgent", "Urgent"),
    ("action_required", "Action required"),
    ("suspicious", "Suspicious - do not act on these"),
    ("fyi", "FYI"),
    ("newsletter", "Newsletters"),
]


def _grouped(briefing: Briefing) -> dict[str, list[EmailTriage]]:
    groups: dict[str, list[EmailTriage]] = {key: [] for key, _ in SECTION_ORDER}
    for t in briefing.emails:
        groups[t.category].append(t)
    return groups


def to_text(
    briefing: Briefing, emails: list[EmailItem], events: list[EventItem], now: datetime
) -> str:
    by_id = {e.id: e for e in emails}
    out = [f"Daily briefing - {now:%A %Y-%m-%d}", briefing.headline, ""]

    if briefing.top_items:
        out.append("Top items:")
        out += [f"  {i}. {item}" for i, item in enumerate(briefing.top_items, start=1)]
        out.append("")

    out.append(f"Calendar ({len(events)}):")
    out += [f"  {ev.when():<13} {ev.subject}" for ev in events] or ["  (nothing scheduled)"]
    out += [f"  note: {n}" for n in briefing.calendar_notes]
    out.append("")

    for key, title in SECTION_ORDER:
        items = _grouped(briefing)[key]
        if not items:
            continue
        out.append(f"{title} ({len(items)}):")
        for t in items:
            e = by_id[t.id]
            out.append(f"  - {e.sender_name or e.sender_address}: {e.subject}")
            if key == "newsletter":
                continue
            out.append(f"      {t.summary}")
            if t.action:
                out.append(f"      -> {t.action}")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def to_html(
    briefing: Briefing, emails: list[EmailItem], events: list[EventItem], now: datetime
) -> str:
    by_id = {e.id: e for e in emails}
    h = [
        '<div style="font-family:Segoe UI,Arial,sans-serif;max-width:680px">',
        f"<h2>Daily briefing - {now:%A %Y-%m-%d}</h2>",
        f"<p><strong>{escape(briefing.headline)}</strong></p>",
    ]
    if briefing.top_items:
        h.append("<h3>Top items</h3><ol>")
        h += [f"<li>{escape(item)}</li>" for item in briefing.top_items]
        h.append("</ol>")

    h.append(f"<h3>Calendar ({len(events)})</h3><ul>")
    h += [f"<li><code>{escape(ev.when())}</code> {escape(ev.subject)}</li>" for ev in events]
    if not events:
        h.append("<li>Nothing scheduled</li>")
    h += [f"<li><em>{escape(n)}</em></li>" for n in briefing.calendar_notes]
    h.append("</ul>")

    for key, title in SECTION_ORDER:
        items = _grouped(briefing)[key]
        if not items:
            continue
        color = "#b00020" if key in ("urgent", "suspicious") else "#333"
        h.append(f'<h3 style="color:{color}">{escape(title)} ({len(items)})</h3><ul>')
        for t in items:
            e = by_id[t.id]
            who = escape(e.sender_name or e.sender_address)
            line = f"<li><strong>{who}</strong>: {escape(e.subject)}"
            if key != "newsletter":
                line += f"<br>{escape(t.summary)}"
                if t.action:
                    line += f"<br>&rarr; {escape(t.action)}"
            h.append(line + "</li>")
        h.append("</ul>")

    h.append(
        '<p style="color:#888;font-size:12px">Generated by an AI assistant. '
        "Verify important details in the original messages.</p></div>"
    )
    return "\n".join(h)
